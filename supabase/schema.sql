create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text not null default '',
  phone text not null default '',
  role text not null default 'customer' check (role in ('customer','staff','admin')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create index profiles_role_idx on public.profiles(role);

create or replace function public.is_staff() returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from profiles where id=auth.uid() and role in ('staff','admin') and active=true)
$$;
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from profiles where id=auth.uid() and role='admin' and active=true)
$$;
create or replace function public.protect_profile_role() returns trigger language plpgsql security definer set search_path=public as $$
begin
  if (new.role is distinct from old.role or new.active is distinct from old.active or new.email is distinct from old.email)
     and auth.uid() is not null and not public.is_admin() then
    raise exception 'Only an administrator can change role, email or account status';
  end if;
  return new;
end $$;
create trigger protect_profile before update on public.profiles for each row execute function public.protect_profile_role();

create or replace function public.new_auth_user() returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,email,full_name,phone)
    values(new.id,coalesce(new.email,''),left(coalesce(new.raw_user_meta_data->>'full_name',''),140),left(coalesce(new.raw_user_meta_data->>'phone',''),30));
  return new;
end $$;
create trigger auth_user_created after insert on auth.users for each row execute function public.new_auth_user();

