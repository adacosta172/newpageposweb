create or replace function public.compute_order() returns trigger language plpgsql security definer set search_path=public as $$
declare v_subtotal numeric(12,2); v_paid numeric(12,2);
begin
  select coalesce(sum(quantity*unit_price),0) into v_subtotal from public.order_items where order_id=new.id;
  select coalesce(sum(amount),0) into v_paid from public.payments where order_id=new.id and status='confirmed';
  new.subtotal:=v_subtotal;
  new.total:=greatest(0,v_subtotal-new.discount)*(1+new.tax_rate/100);
  new.total:=round(new.total,2);
  new.amount_paid:=v_paid;
  new.updated_at:=now();
  return new;
end $$;
create trigger order_totals before insert or update on public.orders for each row execute function public.compute_order();
create or replace function public.recalculate_order() returns trigger language plpgsql security definer set search_path=public as $$
begin
  update public.orders set updated_at=now() where id=coalesce(new.order_id,old.order_id);
  return null;
end $$;
create trigger recalc_on_items after insert or update or delete on public.order_items for each row execute function public.recalculate_order();
create trigger recalc_on_payments after insert or update or delete on public.payments for each row execute function public.recalculate_order();
create or replace function public.audit_order() returns trigger language plpgsql security definer set search_path=public as $$
begin
  if tg_op='INSERT' then
    insert into public.activity_log(actor_id,action,entity,entity_id) values(auth.uid(),'order.created','order',new.id);
  elsif new.status is distinct from old.status then
    insert into public.activity_log(actor_id,action,entity,entity_id) values(auth.uid(),'order.status.'||new.status,'order',new.id);
  end if;
  return null;
end $$;
create trigger log_order after insert or update on public.orders for each row execute function public.audit_order();
create or replace function public.audit_payment() returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.activity_log(actor_id,action,entity,entity_id) values(auth.uid(),'payment.'||new.status,'payment',new.id);
  return null;
end $$;
create trigger log_payment after insert on public.payments for each row execute function public.audit_payment();

