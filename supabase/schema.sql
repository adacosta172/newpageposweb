-- Transaction-safe order creation with validated line items. No partial orders if line insertion fails.
create or replace function public.create_newpage_order(
  p_title text, p_notes text, p_items jsonb, p_source text,
  p_contact_name text default '', p_contact_phone text default '',
  p_due_date date default null, p_discount numeric default 0,
  p_tax_rate numeric default 0
) returns uuid language plpgsql security definer set search_path=public as $$
declare v_actor uuid := auth.uid(); v_staff boolean; v_order uuid; v_item jsonb; v_price numeric; v_qty numeric; v_count int;
begin
  if v_actor is null then raise exception 'Sign in first'; end if;
  if not exists(select 1 from profiles where id=v_actor and active=true) then raise exception 'Inactive account'; end if;
  v_staff:=public.is_staff();
  if p_source not in ('online','walkin') then raise exception 'Invalid source'; end if;
  if not v_staff and p_source<>'online' then raise exception 'Staff permissions required'; end if;
  if char_length(trim(coalesce(p_title,''))) not between 2 and 200 then raise exception 'Enter a job title'; end if;
  if jsonb_typeof(p_items)<>'array' then raise exception 'At least one item is required'; end if;
  v_count:=jsonb_array_length(p_items);
  if v_count<1 or v_count>25 then raise exception 'Enter 1 to 25 items'; end if;
  if v_staff and p_source='walkin' and char_length(trim(coalesce(p_contact_name,'')))<2 then raise exception 'Customer name is required'; end if;
  if not v_staff then p_discount:=0; p_tax_rate:=0; end if;
  if p_discount<0 or p_tax_rate<0 or p_tax_rate>100 then raise exception 'Invalid discount or tax'; end if;
  insert into orders(title,notes,source,contact_name,contact_phone,customer_id,created_by,due_date,discount,tax_rate)
  values(trim(p_title),left(coalesce(p_notes,''),2500),p_source,
    case when v_staff then left(p_contact_name,160) else '' end,
    case when v_staff then left(p_contact_phone,40) else '' end,
    case when v_staff and p_source='walkin' then null else v_actor end,
    v_actor,p_due_date,p_discount,p_tax_rate)
  returning id into v_order;
  for v_item in select value from jsonb_array_elements(p_items) loop
    if length(trim(coalesce(v_item->>'description','')))<2 then raise exception 'Each item must have a description'; end if;
    v_qty:=(v_item->>'quantity')::numeric;
    v_price:=case when v_staff then coalesce((v_item->>'unit_price')::numeric,0) else 0 end;
    if v_qty<=0 or v_qty>100000 or v_price<0 or v_price>100000000 then raise exception 'Invalid quantity or unit price'; end if;
    insert into order_items(order_id,description,specs,quantity,unit_price)
      values(v_order,left(v_item->>'description',300),left(coalesce(v_item->>'specs',''),600),v_qty,v_price);
  end loop;
  return v_order;
end $$;
grant execute on function public.create_newpage_order(text,text,jsonb,text,text,text,date,numeric,numeric) to authenticated;

-- Serialized financial check. A confirmed manual or gateway payment cannot exceed the balance.
create or replace function public.check_payment_balance() returns trigger language plpgsql security definer set search_path=public as $$
declare v_total numeric; v_paid numeric;
begin
  if new.status<>'confirmed' then return new; end if;
  select total into v_total from public.orders where id=new.order_id for update;
  if v_total is null then raise exception 'Order not found'; end if;
  select coalesce(sum(amount),0) into v_paid from public.payments where order_id=new.order_id and status='confirmed' and id<>new.id;
  if v_paid+new.amount>v_total+0.009 then raise exception 'Payment exceeds outstanding balance'; end if;
  return new;
end $$;
create trigger payment_guard before insert or update on public.payments for each row execute function public.check_payment_balance();

